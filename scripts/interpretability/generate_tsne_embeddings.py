#!/usr/bin/env python3
"""Extract clean/PGD latent features and compute paired t-SNE embeddings.

This runner reuses the model-specific PGD archives generated by
``transfer_attack.py``.  Clean and adversarial examples are passed through the
same checkpoint, and their late-layer features are embedded jointly so that
the two sets share one t-SNE coordinate system.

The default invocation processes every test example for all five models and
all four MedMNIST datasets used in this repository.  Outputs are resumable:
existing feature and t-SNE files are reused unless ``--overwrite`` is passed.
"""

import argparse
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np
import torch
import torch.nn.functional as functional
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE
from sklearn.preprocessing import StandardScaler

from models import bpcapsnet as bpcaps
from models import capsnet as caps
from models.MedViT import MedViT_small
from models.resnets import ResNet18, ResNet50

DEFAULT_DATASETS = (
    "bloodmnist",
    "breastmnist",
    "pneumoniamnist",
    "nodulemnist3d",
)
DEFAULT_MODELS = ("resnet18", "resnet50", "vit", "caps", "bpcaps")
MODEL_DISPLAY_NAMES = {
    "resnet18": "ResNet-18",
    "resnet50": "ResNet-50",
    "vit": "MedViT",
    "caps": "CapsNet",
    "bpcaps": "BP-CapsNet",
}


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=DEFAULT_DATASETS,
        default=list(DEFAULT_DATASETS),
    )
    parser.add_argument(
        "--models",
        nargs="+",
        choices=DEFAULT_MODELS,
        default=list(DEFAULT_MODELS),
    )
    parser.add_argument("--epsilon", type=float, default=0.016)
    parser.add_argument(
        "--batch-size",
        type=int,
        default=32,
        help="Inference batch size; reduce this if a large-input model exhausts GPU memory",
    )
    parser.add_argument(
        "--device",
        default=None,
        help="PyTorch device (default: cuda when available, otherwise cpu)",
    )
    parser.add_argument("--seed", type=int, default=665)
    parser.add_argument("--perplexity", type=float, default=30.0)
    parser.add_argument("--tsne-iterations", type=int, default=1000)
    parser.add_argument("--pca-components", type=int, default=50)
    parser.add_argument(
        "--max-samples",
        type=int,
        default=None,
        help="Optional stratified cap per dataset; the default uses every sample",
    )
    parser.add_argument(
        "--checkpoint-dir", type=Path, default=ROOT / "checkpoints"
    )
    parser.add_argument(
        "--attack-data-dir", type=Path, default=ROOT / "transfer_attack_data"
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "latent_space" / "pgd_eps_0.016",
    )
    parser.add_argument(
        "--skip-tsne",
        action="store_true",
        help="Save raw latent features only",
    )
    parser.add_argument(
        "--overwrite", action="store_true", help="Regenerate existing outputs"
    )
    return parser.parse_args()


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True


def epsilon_tag(epsilon):
    return "{:g}".format(epsilon)


def archive_path(attack_data_dir, dataset, model, epsilon):
    return attack_data_dir / "{}_{}_pgd_eps_{}_test.npz".format(
        dataset, model, epsilon_tag(epsilon)
    )


def checkpoint_path(checkpoint_dir, dataset, model):
    resize_tag = "_224" if model == "vit" else ""
    return checkpoint_dir / "{}_{}{}_best_model.pth".format(
        model, dataset, resize_tag
    )


def build_model(model_name, n_channels, n_classes):
    if model_name == "resnet18":
        return ResNet18(in_channels=n_channels, num_classes=n_classes)
    if model_name == "resnet50":
        return ResNet50(in_channels=n_channels, num_classes=n_classes)
    if model_name == "vit":
        return MedViT_small(n_channels=n_channels, num_classes=n_classes)
    if model_name == "caps":
        return caps.CapsNet(n_channels, n_classes)
    if model_name == "bpcaps":
        return bpcaps.BPCapsNet(n_channels, n_classes)
    raise ValueError("Unsupported model: {}".format(model_name))


def load_attack_archive(path, dataset, model, epsilon):
    if not path.is_file():
        raise FileNotFoundError("Missing PGD archive: {}".format(path))
    with np.load(path, allow_pickle=False) as archive:
        required = {"clean_images", "adversarial_images", "labels"}
        missing = required.difference(archive.files)
        if missing:
            raise ValueError("{} is missing keys: {}".format(path, sorted(missing)))
        clean = archive["clean_images"].astype(np.float32, copy=False)
        adversarial = archive["adversarial_images"].astype(np.float32, copy=False)
        labels = archive["labels"].reshape(-1).astype(np.int64, copy=False)
        stored_dataset = str(archive["data_flag"].item())
        stored_model = str(archive["source_model"].item())
        stored_attack = str(archive["attack"].item())
        stored_epsilon = float(archive["epsilon"].item())

    if clean.shape != adversarial.shape or len(clean) != len(labels):
        raise ValueError("Mismatched image/label shapes in {}".format(path))
    if stored_dataset != dataset or stored_model != model:
        raise ValueError(
            "Archive metadata mismatch in {}: {}/{}".format(
                path, stored_dataset, stored_model
            )
        )
    if stored_attack.lower() != "pgd" or not np.isclose(stored_epsilon, epsilon):
        raise ValueError(
            "Expected PGD epsilon {}, found {} epsilon {} in {}".format(
                epsilon, stored_attack, stored_epsilon, path
            )
        )
    max_linf = float(np.max(np.abs(adversarial - clean)))
    if max_linf > epsilon + max(1e-6, epsilon * 1e-5):
        raise ValueError(
            "Perturbation budget exceeded in {}: {:.8f} > {:.8f}".format(
                path, max_linf, epsilon
            )
        )
    return clean, adversarial, labels, max_linf


def stratified_indices(labels, max_samples, seed):
    indices = np.arange(len(labels), dtype=np.int64)
    if max_samples is None or max_samples >= len(labels):
        return indices
    if max_samples < len(np.unique(labels)):
        raise ValueError("--max-samples must be at least the number of classes")

    rng = np.random.default_rng(seed)
    selected = []
    classes, counts = np.unique(labels, return_counts=True)
    quotas = np.floor(max_samples * counts / counts.sum()).astype(int)
    quotas = np.maximum(quotas, 1)
    while quotas.sum() > max_samples:
        candidate = int(np.argmax(quotas))
        if quotas[candidate] > 1:
            quotas[candidate] -= 1
    while quotas.sum() < max_samples:
        remaining = counts - quotas
        quotas[int(np.argmax(remaining))] += 1
    for label, quota in zip(classes, quotas):
        class_indices = indices[labels == label]
        selected.extend(rng.choice(class_indices, size=quota, replace=False))
    return np.sort(np.asarray(selected, dtype=np.int64))


def latent_layer(model, model_name):
    # These are the same late-layer locations used by latent_space.py.
    if model_name.startswith("resnet"):
        return model.layer4, "layer4"
    if model_name == "vit":
        return model.avgpool, "avgpool"
    if model_name == "caps":
        return model.digit_caps, "digit_caps"
    if model_name == "bpcaps":
        return model.routing_module, "routing_module"
    raise ValueError("Unsupported model: {}".format(model_name))


def extract_features(model, model_name, images, batch_size, device):
    captured = {}
    module, layer_name = latent_layer(model, model_name)

    def hook_fn(_module, _inputs, output):
        captured["value"] = output[0] if model_name == "bpcaps" else output

    hook = module.register_forward_hook(hook_fn)
    batches = []
    model.eval()
    try:
        with torch.inference_mode():
            for start in range(0, len(images), batch_size):
                inputs = torch.from_numpy(images[start : start + batch_size]).to(
                    device, non_blocking=True
                )
                if model_name == "vit":
                    inputs = functional.interpolate(
                        inputs, size=(224, 224), mode="nearest"
                    )
                model(inputs)
                latent = captured.get("value")
                if latent is None:
                    raise RuntimeError("The {} hook did not run".format(layer_name))
                batches.append(latent.detach().flatten(start_dim=1).cpu().numpy())
    finally:
        hook.remove()
    return np.concatenate(batches).astype(np.float32, copy=False), layer_name


def save_features(
    output_path,
    clean_features,
    adversarial_features,
    labels,
    indices,
    dataset,
    model,
    epsilon,
    max_linf,
    layer_name,
    checkpoint,
    archive,
):
    np.savez_compressed(
        output_path,
        clean_latent=clean_features,
        adversarial_latent=adversarial_features,
        labels=labels,
        test_indices=indices,
        dataset=np.array(dataset),
        model=np.array(model),
        model_display_name=np.array(MODEL_DISPLAY_NAMES[model]),
        attack=np.array("pgd"),
        epsilon=np.array(epsilon, dtype=np.float64),
        max_linf=np.array(max_linf, dtype=np.float64),
        latent_layer=np.array(layer_name),
        checkpoint=np.array(str(checkpoint.resolve())),
        attack_archive=np.array(str(archive.resolve())),
    )


def compute_tsne(clean_features, adversarial_features, args):
    combined = np.concatenate([clean_features, adversarial_features], axis=0)
    combined = StandardScaler(copy=False).fit_transform(combined).astype(
        np.float32, copy=False
    )

    pca_components = min(
        args.pca_components, combined.shape[1], combined.shape[0] - 1
    )
    if pca_components < combined.shape[1]:
        combined = PCA(
            n_components=pca_components,
            random_state=args.seed,
            svd_solver="randomized",
        ).fit_transform(combined)

    perplexity = min(args.perplexity, (len(combined) - 1) / 3.0)
    if perplexity <= 0:
        raise ValueError("Not enough samples to compute t-SNE")
    coordinates = TSNE(
        n_components=2,
        perplexity=perplexity,
        n_iter=args.tsne_iterations,
        init="pca",
        learning_rate=200.0,
        random_state=args.seed,
        method="barnes_hut",
    ).fit_transform(combined)
    split = len(clean_features)
    return (
        coordinates[:split].astype(np.float32, copy=False),
        coordinates[split:].astype(np.float32, copy=False),
        pca_components,
        perplexity,
    )


def process_pair(dataset, model_name, args, device):
    pair_dir = args.output_dir / dataset / model_name
    pair_dir.mkdir(parents=True, exist_ok=True)
    feature_path = pair_dir / "latent_features.npz"
    tsne_path = pair_dir / "tsne_embeddings.npz"
    archive = archive_path(args.attack_data_dir, dataset, model_name, args.epsilon)
    checkpoint = checkpoint_path(args.checkpoint_dir, dataset, model_name)

    if not checkpoint.is_file():
        raise FileNotFoundError("Missing checkpoint: {}".format(checkpoint))

    if feature_path.is_file() and not args.overwrite:
        print("Reusing {}".format(feature_path), flush=True)
        with np.load(feature_path, allow_pickle=False) as saved:
            clean_features = saved["clean_latent"]
            adversarial_features = saved["adversarial_latent"]
            labels = saved["labels"]
            indices = saved["test_indices"]
    else:
        clean, adversarial, labels, max_linf = load_attack_archive(
            archive, dataset, model_name, args.epsilon
        )
        indices = stratified_indices(labels, args.max_samples, args.seed)
        clean = clean[indices]
        adversarial = adversarial[indices]
        labels = labels[indices]
        n_classes = int(labels.max()) + 1
        network = build_model(model_name, clean.shape[1], n_classes).to(device)
        state = torch.load(checkpoint, map_location=device)
        network.load_state_dict(state["net"], strict=True)

        print(
            "Extracting {} / {} ({} paired samples)".format(
                dataset, model_name, len(labels)
            ),
            flush=True,
        )
        clean_features, layer_name = extract_features(
            network, model_name, clean, args.batch_size, device
        )
        adversarial_features, _ = extract_features(
            network, model_name, adversarial, args.batch_size, device
        )
        save_features(
            feature_path,
            clean_features,
            adversarial_features,
            labels,
            indices,
            dataset,
            model_name,
            args.epsilon,
            max_linf,
            layer_name,
            checkpoint,
            archive,
        )
        print("Saved {}".format(feature_path), flush=True)
        del network, clean, adversarial
        if device.type == "cuda":
            torch.cuda.empty_cache()

    if args.skip_tsne:
        return
    if tsne_path.is_file() and not args.overwrite:
        print("Reusing {}".format(tsne_path), flush=True)
        return

    print("Computing joint t-SNE for {} / {}".format(dataset, model_name), flush=True)
    clean_tsne, adversarial_tsne, pca_components, perplexity = compute_tsne(
        clean_features, adversarial_features, args
    )
    np.savez_compressed(
        tsne_path,
        clean_tsne=clean_tsne,
        adversarial_tsne=adversarial_tsne,
        labels=labels,
        test_indices=indices,
        dataset=np.array(dataset),
        model=np.array(model_name),
        model_display_name=np.array(MODEL_DISPLAY_NAMES[model_name]),
        attack=np.array("pgd"),
        epsilon=np.array(args.epsilon, dtype=np.float64),
        joint_fit=np.array(True),
        standardized=np.array(True),
        pca_components=np.array(pca_components, dtype=np.int64),
        perplexity=np.array(perplexity, dtype=np.float64),
        iterations=np.array(args.tsne_iterations, dtype=np.int64),
        random_state=np.array(args.seed, dtype=np.int64),
        source_features=np.array(str(feature_path.resolve())),
    )
    print("Saved {}".format(tsne_path), flush=True)


def main():
    args = parse_args()
    if args.batch_size < 1:
        raise ValueError("--batch-size must be positive")
    if args.pca_components < 1:
        raise ValueError("--pca-components must be positive")
    if args.tsne_iterations < 250:
        raise ValueError("--tsne-iterations must be at least 250")
    if args.output_dir == ROOT / "latent_space" / "pgd_eps_0.016":
        args.output_dir = ROOT / "latent_space" / (
            "pgd_eps_{}".format(epsilon_tag(args.epsilon))
        )

    set_seed(args.seed)
    device = torch.device(
        args.device or ("cuda" if torch.cuda.is_available() else "cpu")
    )
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is not available")
    print("Using device: {}".format(device), flush=True)
    print("Output directory: {}".format(args.output_dir), flush=True)

    for dataset in args.datasets:
        for model_name in args.models:
            process_pair(dataset, model_name, args, device)


if __name__ == "__main__":
    main()
